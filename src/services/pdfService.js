// ── Severity stage config ────────────────────────────────────────────────────
const SEVERITY_STAGES = ['Low', 'Medium', 'High', 'Critical'];
const SEVERITY_COLORS = {
  Low:      { bg: '#00c853', text: '#fff' },
  Medium:   { bg: '#ffc107', text: '#000' },
  High:     { bg: '#ff6d00', text: '#fff' },
  Critical: { bg: '#cc0000', text: '#fff' },
};

const buildSeverityStages = (severity) => {
  const activeIndex = SEVERITY_STAGES.indexOf(severity);
  const colors = SEVERITY_COLORS[severity] || SEVERITY_COLORS.High;
  const stages = SEVERITY_STAGES.map((stage, i) => {
    const isActive = i === activeIndex;
    const isPast   = i < activeIndex;
    const sc       = SEVERITY_COLORS[stage];
    const bg       = isActive ? sc.bg : isPast ? `${sc.bg}66` : '#e0e0e0';
    const tc       = isActive ? sc.text : isPast ? '#555' : '#bbb';
    return `<div style="flex:1;text-align:center;padding:8px 4px;border-radius:8px;background:${bg};color:${tc};font-weight:${isActive?900:600};font-size:${isActive?13:11}px;border:${isActive?`2px solid ${sc.bg}`:'2px solid transparent'};">${isActive?`<div style="font-size:8px;font-weight:900;letter-spacing:1px;margin-bottom:2px;">▼ CURRENT</div>`:''}${stage.toUpperCase()}</div>`;
  });
  return `<div style="display:flex;gap:5px;margin-top:6px;">${stages.join('')}</div><div style="margin-top:6px;font-size:11px;color:#555;">Classified as <strong style="color:${colors.bg};">${severity} Priority</strong></div>`;
};

