export const generateFIRPDF = async (fir) => {
  // ── Convert local plate photo to base64 data URI so it renders in the PDF ──
  // expo-print's WebView renderer cannot access file:// URIs — only data: URIs work.
  // Strategy: copy to permanent app dir first (cache URIs can vanish), then read as base64.
  let platePhotoDataUri = null;
  if (fir.platePhotoUri) {
    try {
      console.log('[PDF] Plate photo original URI:', fir.platePhotoUri);

      // Step 1: ensure the source file exists
      const info = await FileSystem.getInfoAsync(fir.platePhotoUri);
      console.log('[PDF] Plate photo file info:', JSON.stringify(info));

      if (info.exists) {
        // Step 2: copy to permanent document directory so it doesn't get GC'd
        const destDir  = FileSystem.documentDirectory + 'sahaas_evidence/';
        const destPath = destDir + `plate_${Date.now()}.jpg`;
        await FileSystem.makeDirectoryAsync(destDir, { intermediates: true }).catch(() => {});
        await FileSystem.copyAsync({ from: fir.platePhotoUri, to: destPath });

        // Step 3: read as base64
        const base64 = await FileSystem.readAsStringAsync(destPath, {
          encoding: FileSystem.EncodingType.Base64,
        });
        platePhotoDataUri = `data:image/jpeg;base64,${base64}`;
        console.log(`[PDF] ✅ Plate photo embedded as base64 (${Math.round(base64.length / 1024)} KB)`);
      } else {
        console.warn('[PDF] ⚠️ Plate photo file does not exist at URI:', fir.platePhotoUri);
      }
    } catch (e) {
      console.error('[PDF] ❌ Plate photo base64 failed:', e.message, e);
    }
  }

  const evidenceWithVideo = [
    ...(fir.evidenceList || []),
    (fir.videoUri || fir.videoUrl)
      ? `📹 Incident Video Recording${fir.videoUrl ? ` — ${fir.videoUrl}` : ''} — ${fir.incidentTime}`
      : null,
    fir.platePhotoUri
      ? '📸 Vehicle Number Plate Photo — High-resolution capture (see evidence section below)'
      : null,
  ].filter(Boolean);

  const videoFileName = fir.referenceNumber
    ? `SAHAAS_${fir.referenceNumber.replace(/[^A-Z0-9]/gi, '_')}.mp4`
    : 'SAHAAS_incident_video.mp4';

  try {
    const { uri } = await printToFileAsync({
      html: buildFIRHTML({
        ...fir,
        evidenceList: evidenceWithVideo,
        videoFileName,
        // platePhotoDataUri = base64 data URI (null if conversion failed)
        // Keep original hasPlatePhoto so the block always shows when photo was taken
        platePhotoDataUri,
        // Override platePhotoUri with data URI for img src (null = no img tag)
        platePhotoUri: platePhotoDataUri,
      }),
      base64: false,
    });
    return uri;
  } catch (error) {
    console.error('PDF generation error:', error);
    throw error;
  }
};

export const shareFIRPDF = async (uri) => {
  await shareAsync(uri, {
    mimeType: 'application/pdf',
    dialogTitle: 'Share / Download FIR PDF',
    UTI: 'com.adobe.pdf',
  });
};

